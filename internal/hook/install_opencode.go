package hook

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

//go:embed opencode_plugin.ts
var openCodePluginTemplate string

// openCodeMarker identifies plugin files narc generated.
const openCodeMarker = "narc:generated"

// openCodePlugin installs narc as an OpenCode plugin. OpenCode has no
// command hooks: plugins are TypeScript modules it loads at startup.
type openCodePlugin struct{}

func (openCodePlugin) path(o InstallOptions) (string, error) {
	switch o.Scope {
	case ScopeProject:
		return filepath.Join(o.RepoRoot, ".opencode", "plugins", "narc.ts"), nil
	case ScopeUser:
		return filepath.Join(o.Home, ".config", "opencode", "plugins", "narc.ts"), nil
	}
	return "", scopeError("OpenCode", o.Scope, ScopeProject, ScopeUser)
}

// openCodePluginSource renders the plugin for a narc command. The command
// is spawned directly (no shell), so it is a single program path.
func openCodePluginSource(command string) []byte {
	lit, _ := json.Marshal(command)
	return []byte(strings.Replace(openCodePluginTemplate, "__NARC_COMMAND__", string(lit), 1))
}

func (p openCodePlugin) install(o InstallOptions) (Result, error) {
	path, err := p.path(o)
	if err != nil {
		return Result{}, err
	}
	want := openCodePluginSource(o.Command)
	old, exists, err := readIfExists(path)
	if err != nil {
		return Result{}, err
	}
	var res Result
	switch {
	case exists && !bytes.Contains(old, []byte(openCodeMarker)):
		return Result{}, fmt.Errorf("%s exists and was not generated by narc; move it away and retry", path)
	case exists && bytes.Equal(old, want):
		res.Notes = append(res.Notes, "narc's OpenCode plugin in "+path+" is already up to date.")
	default:
		res.Files = append(res.Files, path)
		if !o.DryRun {
			if err := writeFile(path, want, 0o644); err != nil {
				return res, err
			}
		}
	}
	res.Notes = append(res.Notes,
		"OpenCode loads plugins at startup: restart OpenCode.",
		fmt.Sprintf("The plugin runs %q; it must be on the PATH OpenCode sees (or install with an absolute command).", o.Command))
	return res, nil
}

func (p openCodePlugin) uninstall(o InstallOptions) (Result, error) {
	path, err := p.path(o)
	if err != nil {
		return Result{}, err
	}
	old, exists, err := readIfExists(path)
	if err != nil {
		return Result{}, err
	}
	var res Result
	switch {
	case !exists:
		res.Notes = append(res.Notes, "No narc OpenCode plugin at "+path+".")
	case !bytes.Contains(old, []byte(openCodeMarker)):
		res.Notes = append(res.Notes, path+" was not generated by narc; left it alone.")
	default:
		res.Files = append(res.Files, path)
		if !o.DryRun {
			if err := os.Remove(path); err != nil {
				return res, err
			}
		}
	}
	return res, nil
}
