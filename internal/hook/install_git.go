package hook

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/huyth45/narc/internal/git"
)

// gitPreCommit installs narc into the repository's pre-commit hook. narc
// owns only the block between its markers, so an existing shell hook is
// kept and narc runs first.
type gitPreCommit struct{}

const (
	gitBlockBegin = "# >>> narc >>>"
	gitBlockEnd   = "# <<< narc <<<"
)

// gitBlock is narc's part of the hook. It fails open when narc is missing
// (e.g. a GUI git client with a short PATH).
func gitBlock(command string) string {
	q := shellQuote(command)
	return gitBlockBegin + " managed by `narc install git`; `narc uninstall git` removes this block\n" +
		"if command -v " + q + " >/dev/null 2>&1; then\n" +
		"\t" + q + " hook git pre-commit || exit $?\n" +
		"else\n" +
		"\techo \"narc is not installed or not on PATH; skipping its pre-commit check\" >&2\n" +
		"fi\n" +
		gitBlockEnd + "\n"
}

var shellShebang = regexp.MustCompile(`^#!\s*\S*/(?:env\s+(?:-\S+\s+)*)?(?:sh|bash|zsh|dash|ksh)(?:\s|$)`)

// target returns the pre-commit hook file, honoring core.hooksPath. With
// husky (core.hooksPath = .husky/_) it is husky's user script
// .husky/pre-commit, a shell snippet without a shebang.
func (gitPreCommit) target(o InstallOptions) (path string, husky bool, notes []string, err error) {
	if o.Scope == ScopeUser {
		return "", false, nil, errors.New("git hooks are per repository; install them with the project scope")
	}
	repo, err := git.Open(o.RepoRoot)
	if err != nil {
		return "", false, nil, err
	}
	defer repo.Close()
	out, err := repo.Run("rev-parse", "--git-path", "hooks")
	if err != nil {
		return "", false, nil, err
	}
	dir := strings.TrimSpace(string(out))
	if !filepath.IsAbs(dir) {
		dir = filepath.Join(repo.Root, dir)
	}
	if filepath.Base(dir) == "_" && filepath.Base(filepath.Dir(dir)) == ".husky" {
		path = filepath.Join(filepath.Dir(dir), "pre-commit")
		return path, true, []string{"husky manages this repository's hooks (core.hooksPath), so narc goes into " + path + "."}, nil
	}
	if hp, err := repo.Run("config", "--get", "core.hooksPath"); err == nil && strings.TrimSpace(string(hp)) != "" {
		// A hooks directory outside the repository (a global
		// core.hooksPath) is shared by other repositories, which a
		// per-repository install must not change.
		if !insideRepo(repo, dir) {
			return "", false, nil, fmt.Errorf("core.hooksPath points to %s, outside this repository, so a hook there runs for other repositories too; "+
				"add `%s hook git pre-commit` to %s yourself if that is what you want", dir, shellQuote(o.Command), filepath.Join(dir, "pre-commit"))
		}
		notes = append(notes, "core.hooksPath is set, so the hook goes into "+dir+".")
	}
	return filepath.Join(dir, "pre-commit"), false, notes, nil
}

// insideRepo reports whether dir is inside the repository's work tree or
// its git directory (shared by all its worktrees).
func insideRepo(repo *git.Repo, dir string) bool {
	roots := []string{repo.Root, repo.GitDir}
	if out, err := repo.Run("rev-parse", "--git-common-dir"); err == nil {
		common := strings.TrimSpace(string(out))
		if !filepath.IsAbs(common) {
			common = filepath.Join(repo.Root, common)
		}
		roots = append(roots, common)
	}
	dir = evalExisting(filepath.Clean(dir))
	for _, root := range roots {
		if rel, err := filepath.Rel(evalExisting(root), dir); err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return true
		}
	}
	return false
}

func (g gitPreCommit) install(o InstallOptions) (Result, error) {
	path, husky, notes, err := g.target(o)
	if err != nil {
		return Result{}, err
	}
	res := Result{Notes: notes}
	raw, exists, err := readIfExists(path)
	if err != nil {
		return res, err
	}
	old := string(raw)
	block := gitBlock(o.Command)
	var content string
	switch {
	case !exists || strings.TrimSpace(old) == "":
		content = "#!/bin/sh\n" + block
	case strings.Contains(old, gitBlockBegin):
		if content, err = replaceGitBlock(old, block); err != nil {
			return res, fmt.Errorf("%s: %w", path, err)
		}
	case strings.Contains(old, "pre-commit.com"):
		return res, fmt.Errorf("%s is generated by the pre-commit framework, which would overwrite narc's changes; "+
			"add narc to .pre-commit-config.yaml instead:\n%s", path, preCommitFrameworkSnippet(o.Command))
	case husky || shellShebang.MatchString(old):
		content = insertGitBlock(old, block)
		res.Notes = append(res.Notes, "Added narc to the existing hook "+path+"; it runs before the hook's own commands.")
	default:
		return res, fmt.Errorf("%s exists and is not a shell script; add `%s hook git pre-commit` to it yourself", path, shellQuote(o.Command))
	}

	mode := os.FileMode(0o755)
	executable := false
	if st, err := os.Stat(path); err == nil {
		mode = st.Mode().Perm() | 0o111
		executable = st.Mode().Perm()&0o111 == 0o111
	}
	if content == old && executable {
		res.Notes = append(res.Notes, "narc's pre-commit hook in "+path+" is already up to date.")
		return res, nil
	}
	res.Files = append(res.Files, path)
	if o.DryRun {
		return res, nil
	}
	if err := writeFile(path, []byte(content), mode); err != nil {
		return res, err
	}
	// writeFile keeps an existing file's mode; make sure git can run it.
	return res, os.Chmod(path, mode)
}

func (g gitPreCommit) uninstall(o InstallOptions) (Result, error) {
	path, _, _, err := g.target(o)
	if err != nil {
		return Result{}, err
	}
	var res Result
	raw, exists, err := readIfExists(path)
	if err != nil {
		return res, err
	}
	if !exists || !strings.Contains(string(raw), gitBlockBegin) {
		res.Notes = append(res.Notes, "No narc pre-commit hook in "+path+".")
		return res, nil
	}
	rest, err := replaceGitBlock(string(raw), "")
	if err != nil {
		return res, fmt.Errorf("%s: %w", path, err)
	}
	res.Files = append(res.Files, path)
	if o.DryRun {
		return res, nil
	}
	body := rest
	if strings.HasPrefix(body, "#!") {
		body = body[strings.IndexByte(body+"\n", '\n'):]
	}
	if strings.TrimSpace(body) == "" {
		// Only narc's block was there: the hook was narc's.
		return res, os.Remove(path)
	}
	return res, writeFile(path, []byte(rest), 0o755)
}

// insertGitBlock puts narc's block right after the shebang line, so narc
// runs before the hook's own commands.
func insertGitBlock(script, block string) string {
	if !strings.HasPrefix(script, "#!") {
		return block + script
	}
	nl := strings.IndexByte(script, '\n')
	if nl < 0 {
		return script + "\n" + block
	}
	return script[:nl+1] + block + script[nl+1:]
}

// replaceGitBlock replaces narc's block (marker lines included) with
// block; an empty block removes it.
func replaceGitBlock(script, block string) (string, error) {
	start := strings.Index(script, gitBlockBegin)
	if start < 0 {
		return script, nil
	}
	rel := strings.Index(script[start:], gitBlockEnd)
	if rel < 0 {
		return "", errors.New("narc's block has no end marker; remove it by hand and retry")
	}
	end := start + rel + len(gitBlockEnd)
	if end < len(script) && script[end] == '\n' {
		end++
	}
	return script[:start] + block + script[end:], nil
}

func preCommitFrameworkSnippet(command string) string {
	return "  - repo: local\n" +
		"    hooks:\n" +
		"      - id: narc\n" +
		"        name: narc\n" +
		"        entry: " + shellQuote(command) + " hook git pre-commit\n" +
		"        language: system\n" +
		"        pass_filenames: false\n" +
		"        always_run: true"
}
