package all_test

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/tranhuuhuy297/narc/internal/core"
	_ "github.com/tranhuuhuy297/narc/internal/rules/all"
	"github.com/tranhuuhuy297/narc/internal/ruletest"
)

func loadAll(t *testing.T) []*ruletest.Case {
	t.Helper()
	dirs, _ := filepath.Glob("../*/testdata")
	var cases []*ruletest.Case
	for _, d := range dirs {
		cs, err := ruletest.LoadDir(d)
		if err != nil {
			t.Fatal(err)
		}
		cases = append(cases, cs...)
	}
	return cases
}

// TestCorpusAllRules runs every case with every rule registered, catching
// cross-rule false positives that per-package tests cannot see.
func TestCorpusAllRules(t *testing.T) {
	for _, c := range loadAll(t) {
		c := c
		t.Run(c.Name, func(t *testing.T) {
			res := c.Run(nil)
			want := strings.Join(ruletest.InScope(c.Expect), ",")
			got := strings.Join(ruletest.Got(res), ",")
			if want != got {
				t.Errorf("%s: want [%s] got [%s]", c.Path, want, got)
			}
		})
	}
}

// TestAccuracy prints (and with NARC_WRITE_ACCURACY=1 writes) the corpus
// precision/recall table.
func TestAccuracy(t *testing.T) {
	cases := loadAll(t)
	total, per, clean, cleanOK := ruletest.Evaluate(cases)
	var b strings.Builder
	fmt.Fprintf(&b, "| rule | cases | precision | recall |\n|---|---:|---:|---:|\n")
	var ids []string
	for _, r := range core.Rules() {
		ids = append(ids, r.ID)
	}
	sort.Strings(ids)
	for _, id := range ids {
		s := per[id]
		if s == nil {
			continue
		}
		fmt.Fprintf(&b, "| `%s` | %d | %.0f%% | %.0f%% |\n", id, s.TP+s.FN, 100*s.Precision(), 100*s.Recall())
	}
	fmt.Fprintf(&b, "| **all rules** | %d | **%.1f%%** | **%.1f%%** |\n", total.TP+total.FN, 100*total.Precision(), 100*total.Recall())
	summary := fmt.Sprintf("%d cases (%d cheating, %d legitimate). Legitimate cases with zero findings: %d/%d.\n",
		len(cases), len(cases)-clean, clean, cleanOK, clean)
	t.Log("\n" + summary + "\n" + b.String())
	if os.Getenv("NARC_WRITE_ACCURACY") == "1" {
		doc := "# Corpus accuracy\n\nGenerated by `NARC_WRITE_ACCURACY=1 go test ./internal/rules/all -run TestAccuracy`.\n\n" +
			summary + "\n" + b.String()
		if err := os.WriteFile("../../../docs/accuracy.md", []byte(doc), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}
