// minSummaryWidth is the narrowest summary column RulesTable will use.
const minSummaryWidth = 36

// RulesTable writes the rule list for `narc rules`: rules grouped by
// category, each with its default severity and summary.
func RulesTable(w io.Writer, rules []*core.Rule, o Options) error {
	t := newTerm(o)
	t.blank()
	rules = nonNil(rules)
	if len(rules) == 0 {
		t.line(indentFile, "No rules are registered.")
		t.blank()
		return t.flush(w)
	}
	idW := 0
	for _, r := range rules {
		idW = max(idW, textWidth(r.ID))
	}
	idW = min(idW, 28)
	const sevW = len("warning")
	// Summaries get their own column when it is wide enough to read;
	// on narrow terminals they go under the rule instead.
	columns := t.width-(len(indentFinding)+textWidth(t.g.err)+1+idW+2+sevW+2) >= minSummaryWidth
	for _, c := range byCategory(rules) {
		t.line(indentFile, t.p.paint(sBold, categoryTitle(c.name)), t.p.paint(sDim, fmt.Sprintf(" (%d)", len(c.rules))))
		for _, r := range c.rules {
			st := sevStyle(r.Severity)
			summary := firstNonEmpty(r.Summary, r.Title, r.ID)
			if !columns {
				glyph, sev := t.g.sev(r.Severity), r.Severity.String()
				avail := t.width - len(indentFinding) - textWidth(glyph) - 1
				if textWidth(r.ID)+2+len(sev) <= avail {
					t.line(indentFinding, t.p.paint(st, glyph), " ", t.p.paint(sBold, r.ID), "  ", t.p.paint(st, sev))
				} else {
					// Too narrow for both: the severity moves under the ID.
					t.line(indentFinding, t.p.paint(st, glyph), " ", t.p.paint(sBold, t.fit(r.ID, avail)))
					t.line(indentBody, t.p.paint(st, sev))
				}
				t.para(indentBody, indentBody, summary, sNone)
				continue
			}
			lead := indentFinding + t.p.paint(st, t.g.sev(r.Severity)) + " " + t.p.paint(sBold, padRight(r.ID, idW)) +
				"  " + t.p.paint(st, padRight(r.Severity.String(), sevW)) + "  "
			t.para(lead, strings.Repeat(" ", textWidth(lead)), summary, sNone)
		}
		t.blank()
	}
	t.flow(indentFile, []string{t.p.paint(sDim, plural(len(rules), "rule")), t.p.paint(sDim, "narc explain <rule> for details")},
		t.p.paint(sDim, " "+t.g.dot+" "))
	t.blank()
	return t.flush(w)
}

// RulesMarkdown writes the rule reference (docs/rules.md): the severity
// levels, an index table, and a section per rule with its summary, docs,
// fix advice and how to waive it. Each rule's heading is its ID, so
// RuleDocURL anchors resolve.
func RulesMarkdown(w io.Writer, rules []*core.Rule) error {
	rules = nonNil(rules)
	var b strings.Builder
	b.WriteString("<!-- Code generated by `narc rules --format markdown`. DO NOT EDIT. -->\n\n")
	b.WriteString("# narc rules\n\n")
	fmt.Fprintf(&b, "narc ships %s. Every finding names its rule; `narc explain <rule>` prints the same documentation in your terminal.\n\n",
		plural(len(rules), "rule"))

	b.WriteString("| Severity | Verdict | Meaning |\n| --- | --- | --- |\n")
	b.WriteString("| " + mdSevEmoji[core.Error] + " error | BUSTED | High-confidence integrity violation. Fails `narc scan` and blocks agents by default. |\n")
	b.WriteString("| " + mdSevEmoji[core.Warning] + " warning | SUSPICIOUS | Often a cheat, sometimes legitimate: needs a human look. |\n")
	b.WriteString("| " + mdSevEmoji[core.Info] + " info | NOTE | Worth knowing. Never fails a build by default. |\n\n")
	b.WriteString("Change a rule's severity, or turn it off, under `rules:` in `.narc.yml` (for example `any-cast: error` or `retry-added: off`).\n\n")

	b.WriteString("## Index\n\n| Rule | Severity | Category | Summary |\n| --- | --- | --- | --- |\n")
	for _, r := range rules {
		fmt.Fprintf(&b, "| [%s](#%s) | %s %s | %s | %s |\n", mdCell(mdCode(r.ID)), r.ID, mdSev(r.Severity), r.Severity,
			mdCell(r.Category), mdTableText(firstNonEmpty(r.Summary, r.Title)))
	}
	b.WriteString("\n")

	for _, c := range byCategory(rules) {
		fmt.Fprintf(&b, "## %s\n\n", categoryTitle(c.name))
		for _, r := range c.rules {
			fmt.Fprintf(&b, "### %s\n\n", r.ID)
			fmt.Fprintf(&b, "**%s** · %s `%s` · category `%s`\n\n", firstNonEmpty(r.Title, r.ID), mdSev(r.Severity), r.Severity, r.Category)
			if r.Summary != "" {
				b.WriteString(strings.TrimSpace(r.Summary) + "\n\n")
			}
			if d := strings.TrimSpace(r.Docs); d != "" {
				b.WriteString(d + "\n\n")
			}
			if h := strings.TrimSpace(r.Hint); h != "" {
				b.WriteString("**How to fix:** " + h + "\n\n")
			}
			if r.ID != engine.WaiverRuleID {
				fmt.Fprintf(&b, "**Waive** (only with a reason): `narc:allow %s reason=\"...\"` in a comment on or above the line, "+
					"or an `allow:` entry in `.narc.yml`.\n\n", r.ID)
			}
		}
	}
	_, err := io.WriteString(w, strings.TrimRight(b.String(), "\n")+"\n")
	return err
}

// mdTableText puts authored Markdown (a rule summary) in a table cell:
// it is already Markdown, so only pipes and line breaks need care.
func mdTableText(s string) string {
	s = strings.ReplaceAll(strings.TrimSpace(s), "\n", " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

// Explain writes the documentation of one rule for `narc explain <id>`.
func Explain(w io.Writer, r *core.Rule, o Options) error {
	if r == nil {
		return errors.New("report: nil rule")
	}
	t := newTerm(o)
	st := sevStyle(r.Severity)
	t.blank()
	marker := t.g.sev(r.Severity) + " " + r.ID
	title := firstNonEmpty(r.Title, r.ID)
	if avail := t.width - len(indentFile) - textWidth(marker) - 2; textWidth(title) <= avail {
		t.line(indentFile, t.p.paint(bold(st), marker), "  ", t.p.paint(sBold, title))
	} else {
		// Narrow terminal: the title goes on its own line, aligned with
		// the rule ID like the line below it.
		pad := strings.Repeat(" ", textWidth(t.g.sev(r.Severity))+1)
		t.line(indentFile, t.p.paint(bold(st), t.fit(marker, t.width-len(indentFile))))
		t.line(indentFile, pad, t.p.paint(sBold, t.fit(title, t.width-len(indentFile)-len(pad))))
	}
	meta := []string{r.Severity.String()}
	if r.Category != "" {
		meta = append(meta, r.Category)
	}
	t.line(indentFile, strings.Repeat(" ", textWidth(t.g.sev(r.Severity))+1), t.p.paint(sDim, strings.Join(meta, " "+t.g.dot+" ")))
	t.blank()
	if r.Summary != "" {
		t.para(indentFile, indentFile, r.Summary, sNone)
		t.blank()
	}
	if strings.TrimSpace(r.Docs) != "" {
		t.markdown(r.Docs, indentFile)
		t.blank()
	}
	if strings.TrimSpace(r.Hint) != "" {
		t.line(indentFile, t.p.paint(sBold, "How to fix"))
		t.para(indentFinding, indentFinding, r.Hint, sNone)
		t.blank()
	}
	if r.ID != engine.WaiverRuleID {
		t.line(indentFile, t.p.paint(sBold, "If the change is intentional"))
		t.para(indentFinding, indentFinding, "Waive it with a reason, in a comment on the flagged line or the line above:", sNone)
		// Examples and the docs link are meant to be copied, so they are
		// never truncated; the terminal wraps them if it must.
		t.line(indentBody, t.p.paint(sCode, fmt.Sprintf(`// narc:allow %s reason="<why this is fine>"`, r.ID)))
		t.para(indentFinding, indentFinding, "or for whole paths, in .narc.yml:", sNone)
		for _, l := range []string{"allow:", "  - rule: " + r.ID, `    path: "src/legacy/**"`, `    reason: "<why this is fine>"`} {
			t.line(indentBody, t.p.paint(sCode, l))
		}
		t.blank()
	}
	if docs := "Docs: " + RuleDocURL(r.ID); len(indentFile)+textWidth(docs) <= t.width {
		t.line(indentFile, t.p.paint(sDim, docs))
	} else {
		t.line(indentFile, t.p.paint(sDim, "Docs:"))
		t.line(indentFile, t.p.paint(sDim, RuleDocURL(r.ID)))
	}
	t.blank()
	return t.flush(w)
}

var (
	mdHeadingRe = regexp.MustCompile(`^#{1,6}\s+(.*?)\s*#*$`)
	mdListRe    = regexp.MustCompile(`^([-*+]|\d{1,3}[.)])\s+(.*)$`)
	mdLinkRe    = regexp.MustCompile(`\[([^\]]+)\]\(([^)\s]+)\)`)
	mdStrongRe  = regexp.MustCompile(`\*\*([^*]+)\*\*|__([^_]+)__`)
	mdEscapeRe  = regexp.MustCompile("\\\\([!-/:-@\\[-`{-~])")
)

// markdown renders a rule's Markdown docs for the terminal: paragraphs and
// list items are word-wrapped, fenced code gets a gutter, headings are
// bold, and link and emphasis syntax is reduced to plain text.
func (t *term) markdown(md, indent string) {
	var para []string
	lead := ""
	flush := func() {
		if len(para) > 0 {
			t.para(indent+lead, indent+strings.Repeat(" ", textWidth(lead)), mdPlain(strings.Join(para, " ")), sNone)
		}
		para, lead = nil, ""
	}
	fence := ""
	for _, raw := range strings.Split(strings.ReplaceAll(md, "\r\n", "\n"), "\n") {
		line := strings.TrimSpace(raw)
		if fence != "" {
			if strings.HasPrefix(line, fence) && strings.Trim(line, fence[:1]) == "" {
				fence = ""
				continue
			}
			gutter := t.p.paint(sDim, t.g.gutter)
			if strings.TrimSpace(raw) == "" {
				t.line(indent, gutter)
				continue
			}
			t.line(indent, gutter, " ", t.p.paint(sCode, sanitize(strings.TrimRight(raw, " "), false)))
			continue
		}
		switch {
		case strings.HasPrefix(line, "```") || strings.HasPrefix(line, "~~~"):
			flush()
			fence = line[:len(line)-len(strings.TrimLeft(line, line[:1]))]
		case line == "":
			flush()
			t.blank()
		case mdHeadingRe.MatchString(line):
			flush()
			t.line(indent, t.p.paint(sBold, t.fit(mdPlain(mdHeadingRe.FindStringSubmatch(line)[1]), t.width-len(indent))))
		case mdListRe.MatchString(line):
			flush()
			m := mdListRe.FindStringSubmatch(line)
			lead = m[1] + " "
			if strings.ContainsAny(m[1], "-*+") && !t.o.ASCII {
				lead = "• "
			}
			para = []string{m[2]}
		case strings.HasPrefix(line, "|"):
			flush()
			t.line(indent, t.fit(line, t.width-len(indent)))
		default:
			para = append(para, line)
		}
	}
	flush()
}

// mdPlain reduces inline Markdown to terminal text: [text](url) becomes
// "text (url)", **strong** loses its markers and backslash escapes are
// resolved. Code spans keep their backticks so they can be highlighted.
func mdPlain(s string) string {
	s = mdLinkRe.ReplaceAllString(s, "$1 ($2)")
	s = mdStrongRe.ReplaceAllString(s, "$1$2")
	return mdEscapeRe.ReplaceAllString(s, "$1")
}

type category struct {
	name  string
	rules []*core.Rule
}

// byCategory groups rules by category in order of first appearance
// (core.Rules() already sorts by category).
func byCategory(rules []*core.Rule) []category {
	var out []category
	pos := map[string]int{}
	for _, r := range rules {
		i, ok := pos[r.Category]
		if !ok {
			i = len(out)
			pos[r.Category] = i
			out = append(out, category{name: r.Category})
		}
		out[i].rules = append(out[i].rules, r)
	}
	return out
}

// categoryTitle is a category's display name: "tests" → "Tests", "ci" → "CI".
func categoryTitle(c string) string {
	switch c {
	case "":
		return "Other"
	case "ci":
		return "CI"
	}
	r, size := utf8.DecodeRuneInString(c)
	return string(unicode.ToUpper(r)) + c[size:]
}

func nonNil(rules []*core.Rule) []*core.Rule {
	out := make([]*core.Rule, 0, len(rules))
	for _, r := range rules {
		if r != nil && r.ID != "" {
			out = append(out, r)
		}
	}
	return out
}
